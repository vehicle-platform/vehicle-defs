"""Golden wire vectors for the heartbeats 0x081 (HeartbeatRtCore) and 0x082 (HeartbeatSafety), T36.

The vectors are built from an INDEPENDENT path: cantools encodes the payload signals from the
DBC, and the Python reference E2E (`e2e.compute_crc`, D-005) fills the CRC byte. The generated C
pack and protect code is never used here; `tests/test_heartbeat_vectors.py` proves that the C
produces exactly these bytes. Consumers (safety-node, rt-core, hil-bench) copy or read
`vectors/heartbeat_vectors.json` to test their receive and transmit paths against literal bytes.

Regenerate after a heartbeat layout change: `python -m vehicle_codegen.heartbeat_vectors`.
"""

from __future__ import annotations

import itertools
import json
from typing import Any

from vehicle_codegen import config, e2e
from vehicle_codegen.dbc_checks import e2e_data_id, load_dbc

VECTORS_JSON = config.REPO_ROOT / "vectors" / "heartbeat_vectors.json"
# message name -> (signal prefix, DBC node-mode value table names are the same for both)
MESSAGES = {"HeartbeatRtCore": "RT_CORE", "HeartbeatSafety": "SAFETY"}
MODES = {0: "INIT", 1: "NORMAL", 2: "DEGRADED"}
# Valid CRC but not sent by the node today (D-064 item 1): receivers must treat them as DEGRADED.
OTHER_MODES = {3: "SAFE_STATE", 4: "BOOTLOADER", 5: "DIAGNOSTIC", 15: "UNDEFINED"}


def _case(msg, data_id: int, prefix: str, mode: int, errors: int, uptime: int, counter: int):
    data = bytearray(
        msg.encode(
            {
                "E2E_CRC": 0,
                "E2E_COUNTER": counter,
                f"{prefix}_NODE_MODE": mode,
                f"{prefix}_ERROR_COUNT": errors,
                f"{prefix}_UPTIME": uptime,
            },
            scaling=False,
            strict=True,
        )
    )
    data[e2e.CRC_OFFSET] = e2e.compute_crc(data_id, bytes(data))
    return data


def build() -> dict[str, Any]:
    db = load_dbc(config.PLATFORM_DBC)
    out: dict[str, Any] = {
        "_comment": (
            "Golden wire vectors for the platform heartbeats (T36). Generated by "
            "vehicle_codegen.heartbeat_vectors from cantools + the Python reference E2E, "
            "independent of the generated C. `bytes` are the 8 frame bytes as hex, byte 0 "
            "(E2E CRC-8) first. Do not edit by hand."
        ),
        "messages": {},
    }
    for name, prefix in MESSAGES.items():
        msg = db.get_message_by_name(name)
        data_id = e2e_data_id(msg, db)
        grid = itertools.product(MODES, (0, 255), (0, 65535), (0, 15))
        grid_cases = [(m, e, u, c, MODES[m]) for m, e, u, c in grid]
        other_cases = [(m, 0, 0, 0, n) for m, n in OTHER_MODES.items()]
        cases = []
        for mode, errors, uptime, counter, mode_name in grid_cases + other_cases:
            data = _case(msg, data_id, prefix, mode, errors, uptime, counter)
            cases.append(
                {
                    "node_mode": mode,
                    "node_mode_name": mode_name,
                    "error_count": errors,
                    "uptime": uptime,
                    "counter": counter,
                    "bytes": data.hex(),
                }
            )
        out["messages"][name] = {
            "can_id": msg.frame_id,
            "e2e_data_id": data_id,
            "length": msg.length,
            "cases": cases,
        }
    return out


def load(path=VECTORS_JSON) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def render(vectors: dict[str, Any]) -> str:
    return json.dumps(vectors, indent=2) + "\n"


def main() -> None:
    VECTORS_JSON.write_text(render(build()), encoding="utf-8")
    print(f"wrote {VECTORS_JSON}")


if __name__ == "__main__":
    main()
