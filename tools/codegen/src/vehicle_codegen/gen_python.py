BANNER = '"""GENERATED by vehicle-defs tools/codegen from {source}. DO NOT EDIT."""\n'


def _py_bytes(values: list[int]) -> str:
    """Python source for a bytes literal, e.g. bytes([0x10, 0x03])."""
    return "bytes([" + ", ".join(f"0x{b:02X}" for b in values) + "])"


def _signal_entry(sig: Any) -> str:
    """One ``Signal(...)`` source line, exactly what cantools exposes (deterministic repr)."""
    choices = (
        "None"
        if not sig.choices
        else "{" + ", ".join(f"{k}: {str(v)!r}" for k, v in sorted(sig.choices.items())) + "}"
    )
    mux_ids = (
        "None"
        if sig.multiplexer_ids is None
        else "(" + "".join(f"{i}, " for i in sig.multiplexer_ids) + ")"
    )
    return (
        f"        Signal({sig.name!r}, {sig.start}, {sig.length}, {sig.byte_order!r}, "
        f"{bool(sig.is_signed)}, {sig.scale!r}, {sig.offset!r}, {sig.minimum!r}, "
        f"{sig.maximum!r}, {(sig.unit or '')!r}, {tuple(sig.receivers)!r}, {choices}, "
        f"{bool(sig.is_multiplexer)}, {sig.multiplexer_signal!r}, {mux_ids}),"
    )


def generate_platform_py(db: Database) -> str:
    lines = [BANNER.format(source="dbc/platform.dbc"), ""]
    lines += [
        "from typing import NamedTuple",
        "",
        "",
        "class Signal(NamedTuple):",
        '    """One DBC signal as cantools exposes it (E-20 item 1; start = DBC start bit)."""',
        "",
        "    name: str",
        "    start: int",
        "    length: int",
        "    byte_order: str  # 'little_endian' | 'big_endian'",
        "    is_signed: bool",
        "    factor: float  # cantools 'scale'; physical = raw * factor + offset",
        "    offset: float",
        "    minimum: float | None",
        "    maximum: float | None",
        "    unit: str",
        "    receivers: tuple[str, ...]",
        "    choices: dict[int, str] | None  # VAL_ table, raw -> name",
        "    is_multiplexer: bool",
        "    multiplexer_signal: str | None",
        "    multiplexer_ids: tuple[int, ...] | None",
        "",
        "",
    ]
    lines.append("NODE_IDS = {")
    for name, nid in config.NODE_IDS.items():
        lines.append(f'    "{name}": 0x{nid:X},')
    lines += ["}", ""]
    lines.append(f"E2E_TIMEOUT_CYCLES = {config.E2E_TIMEOUT_CYCLES}")
    lines.append(f"E2E_MAX_DELTA_COUNTER = {config.E2E_MAX_DELTA_COUNTER}")
    lines.append("")
    entries = []
    for m in sorted(db.messages, key=lambda m: m.frame_id):
        up = camel_to_snake_case(m.name).upper()
        lines.append(f"{up}_FRAME_ID = 0x{m.frame_id:03X}")
        lines.append(f"{up}_CYCLE_TIME_MS = {cycle_time_ms(m)}")
        data_id = e2e_data_id(m, db) if is_e2e_protected(m, db) else None
        if data_id is not None:
            lines.append(f"{up}_E2E_DATA_ID = 0x{data_id:04X}")
        entries.append(
            f'    "{m.name}": {{"frame_id": 0x{m.frame_id:03X}, "length": {m.length}, '
            f'"cycle_time_ms": {cycle_time_ms(m)}, "sender": "{m.senders[0]}", '
            f'"e2e_data_id": {"None" if data_id is None else f"0x{data_id:04X}"}}},'
        )
    lines += ["", "MESSAGES = {", *entries, "}", ""]
    lines += [
        "# message name -> signals in DBC (start-bit) order; keyed by name like MESSAGES",
        "SIGNALS: dict[str, tuple[Signal, ...]] = {",
    ]
    for m in sorted(db.messages, key=lambda m: m.frame_id):
        lines.append(f'    "{m.name}": (')
        lines += [_signal_entry(sig) for sig in m.signals]
        lines.append("    ),")
    lines += ["}", ""]
    return "\n".join(lines)


def generate_vehicle_py(vehicle: dict[str, Any], derived_doc: dict[str, Any] | None = None) -> str:
    addr = vehicle["addressing"]
    lines = [BANNER.format(source="uds/vehicle_cl250.yaml"), ""]
    lines.append(f"BITRATE = {vehicle['bus']['bitrate']}")
    lines.append(f"REQUEST_ID = 0x{addr['primary']['request_id']:08X}")
    lines.append(f"RESPONSE_ID = 0x{addr['primary']['response_id']:08X}")
    lines.append(f"FALLBACK_REQUEST_ID = 0x{addr['fallback']['request_id']:03X}")
    lines.append(f"FALLBACK_RESPONSE_ID = 0x{addr['fallback']['response_id']:03X}")
    lines.append(f"FALLBACK_VERIFIED = {bool(addr['fallback']['verified'])}")
    lines.append(f"PADDING_BYTE = 0x{vehicle['transport']['padding_byte']:02X}")
    fc = vehicle["transport"]["flow_control"]
    lines.append("# D-059: the one Flow Control frame the tester may send (FC.CTS, byte-exact)")
    lines.append(f"FC_CTS_FRAME = {_py_bytes(list(config.vehicle_fc_frame(vehicle['transport'])))}")
    lines.append(f"MAX_FF_DL = {fc['max_ff_dl']}")
    lines.append(f"FC_MAX_CF_BURST = {config.vehicle_fc_max_cf_burst(vehicle['transport'])}")
    lines.append("# D-059 discovery scan: (name, request, bitmap, after_name, after_id)")
    lines.append("DISCOVERY_SCAN = (")
    for e in vehicle["discovery_scan"]["requests"]:
        after = e.get("after")
        lines.append(
            f'    ("{e["name"]}", {_py_bytes(e["request"])}, {bool(e.get("bitmap"))}, '
            + (f'"{after["name"]}", 0x{after["id"]:02X}' if after else "None, None")
            + "),"
        )
    lines.append(")")
    snap = vehicle["dtc_snapshot"]
    if derived_doc is None:
        derived_doc = load_yaml(config.DERIVED_YAML)
    warm = dtc_warm_idle(vehicle, derived_doc)
    lines.append("# D-080 (provisional): freeze-frame read of a DTC, only when a DTC is present.")
    lines.append("# 0x19 0x01 mask (count); if > 0 0x19 0x02 mask (list); per DTC, at most")
    lines.append("# DTC_MAX_PER_RUN: 0x19 0x04 <DTC> DTC_SNAPSHOT_RECORD, 0x19 0x06 <DTC>")
    lines.append("# DTC_EXT_DATA_RECORD (0xFF = all records).")
    lines.append(f"DTC_STATUS_MASK = 0x{snap['status_mask']:02X}")
    lines.append(f"DTC_MAX_PER_RUN = {snap['max_dtcs_per_run']}")
    lines.append(f"DTC_SNAPSHOT_RECORD = 0x{snap['snapshot_record']:02X}")
    lines.append(f"DTC_EXT_DATA_RECORD = 0x{snap['ext_data_record']:02X}")
    lines.append("# D-080 item 1 (provisional): the second run of each ignition starts when these")
    lines.append(f"# conditions of the D-079 {snap['warm_idle_window']} window held for")
    lines.append(
        "# DTC_WARM_IDLE_MIN_DURATION_MS. (DID name, op, physical value in the DID's unit);"
    )
    lines.append("# an invalid or stale value = not met.")
    lines.append(f"DTC_WARM_IDLE_MIN_DURATION_MS = {warm['min_duration_ms']}")
    lines.append("DTC_WARM_IDLE_CONDITIONS = (")
    for name, _idx, op, value in warm["conditions"]:
        lines.append(f'    ("{name}", "{op}", {value!r}),')
    lines.append(")")
    watch = addr["functional_watch"]["ids"]
    lines.append("# Q-021/D-040: watch-only functional request IDs (id, extended); never sent")
    lines.append(
        "FUNCTIONAL_WATCH_IDS = ("
        + ", ".join(f"(0x{w['id']:X}, {w['id_type'] == 'extended_29bit'})" for w in watch)
        + ",)"
    )
    start = vehicle["session"]["start"]
    tp = vehicle["session"]["tester_present"]
    lines.append(f"SESSION_REQUEST = {_py_bytes(start['request'])}")
    lines.append(f"SESSION_POSITIVE_SID = 0x{start['positive_response_sid']:02X}")
    lines.append(f"SESSION_RETRY_INTERVAL_MS = {start['retry_interval_ms']}")
    lines.append(f"TESTER_PRESENT_REQUEST = {_py_bytes(tp['request'])}")
    lines.append(f"TESTER_PRESENT_PERIOD_MS = {tp['period_ms']}")
    for key in sorted(vehicle["timing"]):
        if key not in ("verified", "evidence"):
            lines.append(f"{key.upper()} = {vehicle['timing'][key]}")
    lines += [
        "",
        "# name -> (did, length, factor_num, factor_den, offset, unit, min, max, poll_ms,",
        "#          priority); priority is the D-043 class, most urgent first in PRIORITIES",
        "PRIORITIES = (" + ", ".join(f'"{p}"' for p in DID_PRIORITIES) + ",)",
    ]
    lines.append("DIDS = {")
    for d in vehicle["dids"]:
        lines.append(
            f'    "{d["name"]}": (0x{d["did"]:04X}, {d["length"]}, {d["factor_num"]}, '
            f'{d["factor_den"]}, {d["offset"]}, "{d["unit"]}", {d["min"]}, {d["max"]}, '
            f'{d["poll_period_ms"]}, "{d["priority"]}"),'
        )
    lines += ["}", ""]
    lines += [
        "# name -> stale_after_ms: a value older than this must not be used or republished",
        "# (the same value as the C table's stale_after_ms; > the DID's poll period)",
        "DID_STALE_AFTER_MS = {",
    ]
    for d in vehicle["dids"]:
        lines.append(f'    "{d["name"]}": {config.did_stale_after_ms(d)},')
    lines += ["}", ""]
    lines += [
        "# name -> verified: the DID's answer was confirmed on the vehicle (the C table's",
        "# `verified`); an unverified DID can be stopped by the tester (D-068 item 2, D-104)",
        "DID_VERIFIED = {",
    ]
    for d in vehicle["dids"]:
        lines.append(f'    "{d["name"]}": {bool(d["verified"])},')
    lines += ["}", ""]
    policy = vehicle["tester_policy"]
    allowed = {e["sid"]: e.get("subfunctions") for e in policy["allowed"]}
    lines.append("# D-020: sid -> allowed sub-functions (None = any)")
    lines.append("ALLOWED_SERVICES = {")
    for sid, subs in allowed.items():
        subs_txt = (
            "None" if subs is None else "frozenset({" + ", ".join(f"0x{s:02X}" for s in subs) + "})"
        )
        lines.append(f"    0x{sid:02X}: {subs_txt},")
    lines += ["}", ""]
    lines += [
        "",
        "def decode(name: str, data: bytes) -> float:",
        '    """Physical value of a DID response payload (bytes after the DID echo)."""',
        "    _, length, num, den, offset, _, lo, hi, _, _ = DIDS[name]",
        "    if len(data) < length:",
        '        raise ValueError(f"{name}: need {length} bytes")',
        '    value = int.from_bytes(data[:length], "big") * num / den + offset',
        "    if not lo <= value <= hi:",
        '        raise ValueError(f"{name}: {value} outside [{lo}, {hi}]")',
        "    return value",
        "",
        "",
        "def request_allowed(payload: bytes) -> bool:",
        '    """D-020 allow-list; payload starts with the SID (no ISO-TP PCI)."""',
        "    if not payload or payload[0] not in ALLOWED_SERVICES:",
        "        return False",
        "    subs = ALLOWED_SERVICES[payload[0]]",
        "    if subs is None:",
        "        return True",
        "    return len(payload) >= 2 and (payload[1] & 0x7F) in subs",
        "",
    ]
    return "\n".join(lines)


def generate_e2e_py() -> str:
    source = inspect.getsource(e2e)
    # A comment, not a docstring: the module starts with its own docstring and a
    # `from __future__` import, which must come before any other statement.
    banner = (
        "# GENERATED by vehicle-defs tools/codegen from "
        "tools/codegen/src/vehicle_codegen/e2e.py. DO NOT EDIT.\n"
    )
    return banner + source


def generate_init_py() -> str:
    return (
        BANNER.format(source="vehicle-defs")
        + "\n# Modules: platform (platform.dbc constants), vehicle_cl250 (CL250 DIDs),\n"
        "# e2e (reference E2E protect/check), uds (ISO 14229 codes, platform servers),\n"
        "# limits (platform_limits.yaml), ble (BLE packet schema, D-061),\n"
        "# vehicle_constants (CL250 constants for the derived signals, D-070),\n"
        "# vehicle_derived (derived signal definitions, D-070),\n"
        "# mailbox (STM32H755 M7<->M4 mailbox layout, D-093).\n"
    )


def generate_limits_py(limits: dict[str, Any]) -> str:
    lines = [BANNER.format(source="limits/platform_limits.yaml"), ""]
    lines.append("# name -> (value, status); rules: limits/platform_limits.yaml")
    lines.append("LIMITS = {")
    for section in LIMIT_KEYS:
        for key, entry in limits[section].items():
            lines.append(f'    "{key}": ({entry["value"]!r}, "{entry["status"]}"),')
    lines += ["}", ""]
    lines.append("# section -> nodes whose platform_limits.h has it (D-041: speed is rt-core's)")
    lines.append("SCOPE = {")
    for section in LIMIT_KEYS:
        nodes = ", ".join(f'"{n}"' for n in limits["scope"][section])
        lines.append(f'    "{section}": ({nodes},),')
    lines += ["}", ""]
    return "\n".join(lines)


