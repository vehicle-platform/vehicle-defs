"""Fault catalog (D-084): faults/catalog.yaml + vehicle/cl250_faults.yaml.

A vehicle-independent, FMEA-style catalog of fault signatures and the per-vehicle list of the
entries that apply (D-078). Codegen refuses an applied entry whose symptom or `needs` signal
defs does not define (invariant 2), enforces the D-084 item 4 advice rules and marks an entry
without a high/medium source as not displayable (item 5, CONFIRM).
"""

from __future__ import annotations

import pprint
import re
from typing import Any

SOURCE = "faults/catalog.yaml + vehicle/cl250_faults.yaml"
PY_BANNER = f'"""GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT."""\n'

SUBSYSTEMS = (
    "battery_starting",
    "charging",
    "ignition",
    "fuel_air",
    "cooling",
    "lubrication",
    "clutch_gearbox",
    "final_drive",
    "brakes_abs",
    "wheels_tyres",
    "suspension_steering",
    "wiring",
    "lighting",
)
ALWAYS_STOP_SUBSYSTEMS = ("brakes_abs", "wheels_tyres", "suspension_steering")
DIRECTIONS = ("up", "down", "unstable", "absent")
CONFIDENCES = ("high", "medium", "low")
SEVERITY_STOP = 8
FORBIDDEN_PHRASES = ("safe to ride", "safe to continue")

_ID = re.compile(r"[A-Z]{3}-[0-9]{3}")
_SIGNAL = re.compile(r"(did|derived|sensor)\.[A-Za-z0-9_]+")
_REQUIRED = (
    "id",
    "subsystem",
    "root_cause",
    "symptoms",
    "needs",
    "rating",
    "detectable_now",
    "advise_stop",
    "rider_text",
    "action",
    "sources",
)
_OPTIONAL = ("residual",)
_RATINGS = ("severity", "occurrence", "detectability")


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def known_signals(vehicle: dict[str, Any], derived: dict[str, Any]) -> set[str]:
    """Every signal name the CL250 defs define: polled DIDs, derived signals, sensors."""
    return (
        {f"did.{d['name']}" for d in vehicle["dids"]}
        | {f"derived.{n}" for n in derived["signals"]}
        | {f"sensor.{n}" for n in derived["sensors"]}
    )


def _check_symptom(label: str, i: int, s: Any, windows: set[str]) -> list[str]:
    where = f"{label} symptom {i}"
    if not isinstance(s, dict):
        return [f"{where}: must be a mapping"]
    errors = [
        f"{where}: unknown key {k!r}"
        for k in s
        if k not in ("signal", "direction", "condition", "window")
    ]
    if not (isinstance(s.get("signal"), str) and _SIGNAL.fullmatch(s["signal"])):
        errors.append(f"{where}: signal must be did.<NAME>, derived.<name> or sensor.<name>")
    if s.get("direction") not in DIRECTIONS:
        errors.append(f"{where}: direction must be one of {', '.join(DIRECTIONS)}")
    if not _text(s.get("condition")):
        errors.append(f"{where}: condition must be a non-empty string")
    if "window" in s and s["window"] not in windows:
        errors.append(f"{where}: window {s['window']!r} is not in derived `windows` (D-079)")
    return errors


def _check_entry(label: str, e: dict[str, Any], windows: set[str]) -> list[str]:
    errors = [f"{label}: missing key {k!r}" for k in _REQUIRED if k not in e]
    errors += [f"{label}: unknown key {k!r}" for k in e if k not in _REQUIRED + _OPTIONAL]
    if errors:
        return errors
    if e["subsystem"] not in SUBSYSTEMS:
        errors.append(f"{label}: subsystem must be one of {', '.join(SUBSYSTEMS)}")
    for key in ("root_cause", "rider_text", "action"):
        if not _text(e[key]):
            errors.append(f"{label}: {key} must be a non-empty string")
    if "residual" in e and not _text(e["residual"]):
        errors.append(f"{label}: residual must be a non-empty string")
    for key in ("detectable_now", "advise_stop"):
        if not isinstance(e[key], bool):
            errors.append(f"{label}: {key} must be true or false")
    symptoms = e["symptoms"]
    if not (isinstance(symptoms, list) and symptoms):
        errors.append(f"{label}: symptoms must be a non-empty list")
    else:
        for i, s in enumerate(symptoms):
            errors += _check_symptom(label, i, s, windows)
    needs = e["needs"]
    if not (
        isinstance(needs, list)
        and needs
        and all(isinstance(n, str) and _SIGNAL.fullmatch(n) for n in needs)
    ):
        errors.append(f"{label}: needs must be a non-empty list of signal names")
    elif isinstance(symptoms, list):
        for s in symptoms:
            if (
                isinstance(s, dict)
                and isinstance(s.get("signal"), str)
                and s["signal"] not in needs
            ):
                errors.append(f"{label}: symptom signal {s['signal']} is not listed in needs")
    rating = e["rating"]
    if not (isinstance(rating, dict) and set(rating) == set(_RATINGS)):
        errors.append(f"{label}: rating must have exactly {', '.join(_RATINGS)}")
    else:
        for k in _RATINGS:
            if not (_is_int(rating[k]) and 1 <= rating[k] <= 10):
                errors.append(f"{label}: rating.{k} must be an integer 1..10")
    sources = e["sources"]
    if not isinstance(sources, list):
        errors.append(f"{label}: sources must be a list")
    else:
        for i, src in enumerate(sources):
            if not (
                isinstance(src, dict)
                and set(src) == {"ref", "confidence"}
                and _text(src["ref"])
                and src["confidence"] in CONFIDENCES
            ):
                errors.append(
                    f"{label}: sources[{i}] must be {{ref, confidence: {'|'.join(CONFIDENCES)}}}"
                )
    errors += _check_advice(label, e)
    return errors


def _stop_required(e: dict[str, Any]) -> bool:
    """D-084 item 4: brakes, steering, tyres, a fuel leak or severity >= 8 advise stopping."""
    severity = e["rating"]["severity"] if isinstance(e["rating"], dict) else 0
    return (
        e["subsystem"] in ALWAYS_STOP_SUBSYSTEMS
        or (e["subsystem"] == "fuel_air" and "leak" in str(e["root_cause"]).lower())
        or (_is_int(severity) and severity >= SEVERITY_STOP)
    )


def _check_advice(label: str, e: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if _stop_required(e) and e["advise_stop"] is not True:
        errors.append(
            f"{label}: brakes/steering/tyres, a fuel leak or severity >= {SEVERITY_STOP} "
            "must set advise_stop: true (D-084 item 4)"
        )
    text = str(e["rider_text"]).lower()
    for phrase in FORBIDDEN_PHRASES:
        if phrase in text:
            errors.append(f"{label}: rider_text must never say {phrase!r} (D-084 item 4)")
    return errors


def check_faults(
    catalog: dict[str, Any],
    applicability: dict[str, Any],
    vehicle: dict[str, Any],
    derived: dict[str, Any],
) -> list[str]:
    """faults/catalog.yaml and vehicle/cl250_faults.yaml against the CL250 defs."""
    if catalog.get("schema_version") != 1:
        return ["faults: catalog schema_version must be 1"]
    if applicability.get("schema_version") != 1:
        return ["faults: cl250_faults schema_version must be 1"]
    entries = catalog.get("entries")
    if not (isinstance(entries, list) and entries):
        return ["faults: `entries` must be a non-empty list"]
    windows = set(derived.get("windows", {}))
    known = known_signals(vehicle, derived)
    errors: list[str] = []
    by_id: dict[str, dict[str, Any]] = {}
    for i, e in enumerate(entries):
        if not isinstance(e, dict):
            errors.append(f"faults entry {i}: must be a mapping")
            continue
        eid = e.get("id")
        label = f"faults {eid}" if isinstance(eid, str) else f"faults entry {i}"
        if not (isinstance(eid, str) and _ID.fullmatch(eid)):
            errors.append(f"{label}: id must match AAA-000")
        elif eid in by_id:
            errors.append(f"{label}: duplicate id")
        else:
            by_id[eid] = e
        errors += _check_entry(label, e, windows)
    applies = applicability.get("applies")
    if not (isinstance(applies, list) and all(isinstance(a, str) for a in applies)):
        return errors + ["faults: `applies` must be a list of ids"]
    if len(set(applies)) != len(applies):
        errors.append("faults: `applies` lists an id twice")
    for aid in applies:
        entry = by_id.get(aid)
        if entry is None:
            errors.append(f"faults: applies {aid} is not a catalog entry")
            continue
        names = [s.get("signal") for s in entry.get("symptoms", []) if isinstance(s, dict)]
        names += entry.get("needs", []) if isinstance(entry.get("needs"), list) else []
        for name in dict.fromkeys(names):
            if isinstance(name, str) and name not in known:
                errors.append(f"faults {aid}: signal {name} is not defined in the CL250 defs")
    return errors


def displayable(entry: dict[str, Any]) -> bool:
    """D-084 item 5: shown to a rider only with a high or medium source, else CONFIRM."""
    return any(s["confidence"] in ("high", "medium") for s in entry["sources"])


def generate_python(catalog: dict[str, Any], applicability: dict[str, Any]) -> str:
    faults = {e["id"]: {**e, "displayable": displayable(e)} for e in catalog["entries"]}
    applies = tuple(applicability["applies"])
    return (
        PY_BANNER
        + "\n# id -> entry (faults/catalog.yaml) + `displayable` (high/medium source, else CONFIRM)\n"
        + "FAULTS = "
        + pprint.pformat(faults, sort_dicts=False, width=96)
        + "\n\n# catalog ids that apply to the CL250 (vehicle/cl250_faults.yaml, D-078)\n"
        + "APPLIES_CL250 = "
        + pprint.pformat(applies, width=96)
        + "\n"
    )
