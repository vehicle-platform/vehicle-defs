"""The position rule (`privacy/position_rule.yaml`, D-076): check and Python generation.

The YAML is the single source for which names count as GPS position data. The generated
`vehicle_defs.position` is pure (no I/O, no dependencies); consumers import it, or (vehicle-mcp,
no defs submodule) vendor the generated file and test it against `privacy/position_vectors.json`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from . import config
from .yaml_checks import load_yaml

SOURCE = "privacy/position_rule.yaml"
_LISTS = ("horizontal_tokens", "vertical_tokens", "relative_last_tokens", "path_segments")


def load_rule(path: Path | str = config.POSITION_RULE_YAML) -> dict[str, Any]:
    return load_yaml(path)


def load_vectors(path: Path | str = config.POSITION_VECTORS_JSON) -> dict[str, Any]:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: top level must be an object")
    return data


def check_rule(rule: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    for key in _LISTS:
        values = rule.get(key)
        if not isinstance(values, list) or not values:
            errors.append(f"position rule: {key} must be a non-empty list")
            continue
        for value in values:
            if not isinstance(value, str) or not value or not value.isalnum():
                errors.append(f"position rule: {key} entry {value!r} must be alphanumeric text")
            elif value != value.lower():
                errors.append(f"position rule: {key} entry {value!r} must be lowercase")
        if len(set(values)) != len(values):
            errors.append(f"position rule: {key} has duplicates")
    both = set(rule.get("horizontal_tokens") or []) & set(rule.get("vertical_tokens") or [])
    if both:
        errors.append(f"position rule: token in both horizontal and vertical: {sorted(both)}")
    return errors


def _set_literal(values: list[str]) -> str:
    return "frozenset({" + ", ".join(f'"{v}"' for v in sorted(values)) + "})"


_TEMPLATE = '''"""GENERATED by vehicle-defs tools/codegen from {source}. DO NOT EDIT.

The position rule (D-076, platform invariant 7): which names are GPS position data and must be
refused, dropped or redacted. Pure functions, standard library only, so a consumer without the
defs submodule can vendor this file and test it against privacy/position_vectors.json.
"""

from __future__ import annotations

import re
from typing import Any

HORIZONTAL_TOKENS = {horizontal}
VERTICAL_TOKENS = {vertical}
RELATIVE_LAST_TOKENS = {relative}
PATH_SEGMENTS = {segments}

_CAMEL_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")
_TOKEN_SPLIT = re.compile(r"[^a-z0-9]+")


def is_position_key(name: str) -> bool:
    """Whether a signal, series, column or VSS path name is a GPS position component.

    A horizontal token anywhere in the name refuses it. A vertical token does too, unless the
    name ends in a relative token (``altitude_change``). camelCase is split too (``gpsLat``) and
    the unsplit name is kept so ``hMSL`` still reads as ``hmsl``. A dot-separated segment equal
    to a path segment (``Vehicle.CurrentLocation.*``, ``GNSS.Position``) refuses the name.
    """
    plain = [token for token in _TOKEN_SPLIT.split(name.lower()) if token]
    split = [token for token in _TOKEN_SPLIT.split(_CAMEL_BOUNDARY.sub("_", name).lower()) if token]
    tokens = set(plain) | set(split)
    if tokens & HORIZONTAL_TOKENS:
        return True
    if any(segment.lower() in PATH_SEGMENTS for segment in name.split(".")):
        return True
    relative = bool(plain) and plain[-1] in RELATIVE_LAST_TOKENS
    return bool(tokens & VERTICAL_TOKENS) and not relative


# Aliases kept so a consumer migrating from its hand-written copy changes only the import.
is_position_name = is_position_key
is_position_path = is_position_key


def drop_position_columns(columns: list[str]) -> list[str]:
    """The columns that are safe to hand on (order kept)."""
    return [column for column in columns if not is_position_key(column)]


def redact(value: Any) -> Any:
    """A copy of ``value`` without position keys at any depth of dicts and lists.

    Only mapping keys are judged; values (strings, numbers) are never inspected. Tuples are
    treated as lists. Everything else is returned unchanged.
    """
    if isinstance(value, dict):
        return {{
            key: redact(item)
            for key, item in value.items()
            if not (isinstance(key, str) and is_position_key(key))
        }}
    if isinstance(value, (list, tuple)):
        return [redact(item) for item in value]
    return value
'''


def generate_python(rule: dict[str, Any]) -> str:
    return _TEMPLATE.format(
        source=SOURCE,
        horizontal=_set_literal(rule["horizontal_tokens"]),
        vertical=_set_literal(rule["vertical_tokens"]),
        relative=_set_literal(rule["relative_last_tokens"]),
        segments=_set_literal(rule["path_segments"]),
    )


def check_vectors(vectors: dict[str, Any]) -> list[str]:
    """Structure of the golden vectors (their results are tested against the generated module)."""
    errors: list[str] = []
    for key, fields in (
        ("is_position_key", ("name", "expected")),
        ("drop_position_columns", ("columns", "expected")),
        ("redact", ("input", "expected")),
    ):
        cases = vectors.get(key)
        if not isinstance(cases, list) or not cases:
            errors.append(f"position vectors: {key} must be a non-empty list")
            continue
        for i, case in enumerate(cases):
            if not isinstance(case, dict) or set(case) != set(fields):
                errors.append(f"position vectors: {key}[{i}] must have exactly {fields}")
    return errors
