"""In-ride alert rules (D-129 item 2): faults/alert_rules.yaml.

Rules are data: a defs signal, a condition, a threshold in the signal's defs unit, debounce,
hysteresis, cooldown and a per-ride cap. Codegen refuses an unknown signal, a unit that differs
from the signal's, an unknown gate, a P0 rule (safety stays on safety-node, invariant 3) and a
linked fault entry that does not exist. Generated for Python and Dart (invariant 2).
"""

from __future__ import annotations

import re
import textwrap
from typing import Any

from vehicle_codegen import faults

SOURCE = "faults/alert_rules.yaml"
PY_BANNER = f'"""GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT."""\n'
DART_BANNER = (
    f"// GENERATED by vehicle-defs tools/codegen from {SOURCE}. DO NOT EDIT.\n"
    "// Regenerate with `make gen`.\n"
)

CLASSES = ("P1", "P2")  # P0 is safety-node only, P3 is the post-ride notifications (D-129 item 1)
CONDITIONS = ("above", "below", "rate_above", "rate_below", "absent")
RATE_CONDITIONS = ("rate_above", "rate_below")
GATE_OPS = ("gt", "ge", "lt", "le", "eq")
STATUSES = ("PROVISIONAL", "TUNED")
CONFIDENCES = faults.CONFIDENCES

_ID = re.compile(r"ALR-[0-9]{3}")
_GATE_NAME = re.compile(r"[a-z][a-z0-9_]*")
_SIGNAL = re.compile(r"(did|derived)\.[A-Za-z0-9_]+")
_RULE_REQUIRED = (
    "id",
    "class",
    "signal",
    "condition",
    "unit",
    "sustain_s",
    "cooldown_s",
    "max_spoken_per_ride",
    "status",
    "source",
)
_RULE_OPTIONAL = (
    "fault_id",
    "text",
    "threshold",
    "rate_window_s",
    "clear_hysteresis",
    "while",
)
_GATE_KEYS = ("signal", "op", "value", "unit", "source")


def _num(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def signal_units(vehicle: dict[str, Any], derived: dict[str, Any]) -> dict[str, str]:
    """did.<NAME> and derived.<name> -> the unit defs gives that signal (catalog resolution)."""
    units = {f"did.{d['name']}": d.get("unit", "") for d in vehicle["dids"]}
    units.update({f"derived.{n}": s.get("unit", "") for n, s in derived["signals"].items()})
    return units


def _check_gate(name: str, gate: Any, units: dict[str, str]) -> list[str]:
    label = f"alert_rules gate {name}"
    if not isinstance(gate, dict):
        return [f"{label}: must be a mapping"]
    errors = [f"{label}: unknown key {k!r}" for k in gate if k not in _GATE_KEYS]
    errors += [f"{label}: missing key {k!r}" for k in _GATE_KEYS if k not in gate]
    if errors:
        return errors
    if not (isinstance(gate["signal"], str) and gate["signal"] in units):
        errors.append(f"{label}: signal {gate['signal']!r} is not a did.* or derived.* defs signal")
    elif gate["unit"] != units[gate["signal"]]:
        errors.append(f"{label}: unit {gate['unit']!r} must be {units[gate['signal']]!r}")
    if gate["op"] not in GATE_OPS:
        errors.append(f"{label}: op must be one of {', '.join(GATE_OPS)}")
    if not _num(gate["value"]):
        errors.append(f"{label}: value must be a number")
    if not _text(gate["source"]):
        errors.append(f"{label}: source must be a non-empty string")
    return errors


def _check_source(label: str, src: Any) -> list[str]:
    if not (
        isinstance(src, dict)
        and set(src) == {"ref", "confidence"}
        and _text(src["ref"])
        and src["confidence"] in CONFIDENCES
    ):
        return [f"{label}: source must be {{ref, confidence: {'|'.join(CONFIDENCES)}}}"]
    return []


def _check_numbers(label: str, r: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    for key in ("sustain_s", "cooldown_s"):
        if not (_num(r[key]) and r[key] > 0):
            errors.append(f"{label}: {key} must be a positive number")
    cap = r["max_spoken_per_ride"]
    if not (isinstance(cap, int) and not isinstance(cap, bool) and cap >= 1):
        errors.append(f"{label}: max_spoken_per_ride must be an integer >= 1")
    cond = r["condition"]
    if cond == "absent":
        for key in ("threshold", "clear_hysteresis", "rate_window_s"):
            if key in r:
                errors.append(f"{label}: an `absent` rule has no {key}")
        return errors
    if not _num(r.get("threshold")):
        errors.append(f"{label}: threshold must be a number")
    hyst = r.get("clear_hysteresis")
    if not (_num(hyst) and hyst >= 0):
        errors.append(f"{label}: clear_hysteresis must be a number >= 0")
    if cond in RATE_CONDITIONS:
        if not (_num(r.get("rate_window_s")) and r["rate_window_s"] > 0):
            errors.append(f"{label}: a {cond} rule needs rate_window_s > 0")
    elif "rate_window_s" in r:
        errors.append(f"{label}: rate_window_s only belongs to rate_above/rate_below")
    return errors


def _check_rule(
    label: str,
    r: dict[str, Any],
    units: dict[str, str],
    gates: dict[str, Any],
    by_fault: dict[str, dict[str, Any]],
) -> list[str]:
    errors = [f"{label}: missing key {k!r}" for k in _RULE_REQUIRED if k not in r]
    errors += [f"{label}: unknown key {k!r}" for k in r if k not in _RULE_REQUIRED + _RULE_OPTIONAL]
    if errors:
        return errors
    if r["class"] == "P0":
        errors.append(f"{label}: P0 is safety-node only and forbidden here (invariant 3)")
    elif r["class"] not in CLASSES:
        errors.append(f"{label}: class must be one of {', '.join(CLASSES)}")
    if r["condition"] not in CONDITIONS:
        errors.append(f"{label}: condition must be one of {', '.join(CONDITIONS)}")
        return errors
    signal = r["signal"]
    if not (isinstance(signal, str) and _SIGNAL.fullmatch(signal) and signal in units):
        errors.append(f"{label}: signal {signal!r} is not a did.* or derived.* defs signal")
    else:
        unit = units[signal]
        want = f"{unit}/min" if r["condition"] in RATE_CONDITIONS else unit
        if r["unit"] != want:
            errors.append(f"{label}: unit {r['unit']!r} must be {want!r} (defs unit of {signal})")
    errors += _check_numbers(label, r)
    for g in r.get("while", []) if isinstance(r.get("while", []), list) else []:
        if g not in gates:
            errors.append(f"{label}: while gate {g!r} is not defined in `gates`")
    if "while" in r and not (isinstance(r["while"], list) and r["while"]):
        errors.append(f"{label}: while must be a non-empty list of gate names")
    elif isinstance(r.get("while"), list) and len(set(r["while"])) != len(r["while"]):
        errors.append(f"{label}: while lists a gate twice")
    errors += _check_text(label, r, by_fault)
    if r["status"] not in STATUSES:
        errors.append(f"{label}: status must be one of {', '.join(STATUSES)}")
    errors += _check_source(label, r["source"])
    if (
        r["status"] == "TUNED"
        and isinstance(r["source"], dict)
        and r["source"].get("confidence") == "low"
    ):
        errors.append(f"{label}: a low-confidence rule must stay PROVISIONAL")
    return errors


def _check_text(label: str, r: dict[str, Any], by_fault: dict[str, dict[str, Any]]) -> list[str]:
    """The alert text: a displayable linked entry's rider_text, else the rule's own `text`."""
    fid = r.get("fault_id")
    entry = None
    if fid is not None:
        entry = by_fault.get(fid) if isinstance(fid, str) else None
        if entry is None:
            return [f"{label}: fault_id {fid!r} is not a catalog entry"]
    own = r.get("text")
    if entry is not None and faults.displayable(entry):
        return [f"{label}: text must be omitted, the entry's rider_text is used"] if own else []
    if not _text(own):
        why = "fault_id is absent" if entry is None else f"{fid} is CONFIRM (not displayable)"
        return [f"{label}: text is required because {why}"]
    low = own.lower()
    return [
        f"{label}: text must never say {p!r} (D-084 item 4)"
        for p in faults.FORBIDDEN_PHRASES
        if p in low
    ]


def check_alert_rules(
    data: dict[str, Any],
    catalog: dict[str, Any],
    vehicle: dict[str, Any],
    derived: dict[str, Any],
) -> list[str]:
    """faults/alert_rules.yaml against the CL250 defs and the fault catalog."""
    if data.get("schema_version") != 1:
        return ["alert_rules: schema_version must be 1"]
    errors = [
        f"alert_rules: unknown key {k!r}"
        for k in data
        if k not in ("schema_version", "gates", "rules")
    ]
    units = signal_units(vehicle, derived)
    gates = data.get("gates")
    if not (isinstance(gates, dict) and gates):
        return errors + ["alert_rules: `gates` must be a non-empty mapping"]
    for name, gate in gates.items():
        if not (isinstance(name, str) and _GATE_NAME.fullmatch(name)):
            errors.append(f"alert_rules gate {name!r}: name must be lower_snake_case")
        errors += _check_gate(str(name), gate, units)
    rules = data.get("rules")
    if not (isinstance(rules, list) and rules):
        return errors + ["alert_rules: `rules` must be a non-empty list"]
    by_fault = {e["id"]: e for e in catalog.get("entries", []) if isinstance(e, dict)}
    seen: set[str] = set()
    for i, r in enumerate(rules):
        if not isinstance(r, dict):
            errors.append(f"alert_rules rule {i}: must be a mapping")
            continue
        rid = r.get("id")
        label = f"alert_rules {rid}" if isinstance(rid, str) else f"alert_rules rule {i}"
        if not (isinstance(rid, str) and _ID.fullmatch(rid)):
            errors.append(f"{label}: id must match ALR-000")
        elif rid in seen:
            errors.append(f"{label}: duplicate id")
        else:
            seen.add(rid)
        errors += _check_rule(label, r, units, gates, by_fault)
    return errors


def resolve(data: dict[str, Any], catalog: dict[str, Any]) -> list[dict[str, Any]]:
    """Rules with every optional key filled and the alert text resolved (checked data only)."""
    by_fault = {e["id"]: e for e in catalog["entries"]}
    out: list[dict[str, Any]] = []
    for r in data["rules"]:
        entry = by_fault.get(r.get("fault_id", ""))
        from_fault = entry is not None and faults.displayable(entry)
        out.append(
            {
                "id": r["id"],
                "alert_class": r["class"],
                "signal": r["signal"],
                "fault_id": r.get("fault_id"),
                "text": entry["rider_text"] if from_fault else r["text"],
                "text_source": "fault" if from_fault else "rule",
                "condition": r["condition"],
                "threshold": None if r["condition"] == "absent" else float(r["threshold"]),
                "unit": r["unit"],
                "rate_window_s": (
                    float(r["rate_window_s"]) if r["condition"] in RATE_CONDITIONS else None
                ),
                "sustain_s": float(r["sustain_s"]),
                "clear_hysteresis": (
                    None if r["condition"] == "absent" else float(r["clear_hysteresis"])
                ),
                "cooldown_s": float(r["cooldown_s"]),
                "max_spoken_per_ride": r["max_spoken_per_ride"],
                "gates": tuple(r.get("while", ())),
                "status": r["status"],
                "source_ref": r["source"]["ref"],
                "source_confidence": r["source"]["confidence"],
            }
        )
    return out


def _gates(data: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        {
            "name": n,
            "signal": g["signal"],
            "op": g["op"],
            "value": float(g["value"]),
            "unit": g["unit"],
            "source": g["source"],
        }
        for n, g in data["gates"].items()
    ]


_PY_CLASSES = '''
@dataclass(frozen=True)
class AlertGate:
    """A named while-condition on one defs signal; an invalid or stale value makes it false."""

    name: str
    signal: str  # did.<NAME> or derived.<name>
    op: str  # gt | ge | lt | le | eq
    value: float
    unit: str
    source: str


@dataclass(frozen=True)
class AlertRule:
    """One in-ride alert rule (D-129). Times in seconds, threshold and hysteresis in `unit`."""

    id: str  # ALR-000
    alert_class: str  # "P1" urgent, spoken at once + banner | "P2" advisory, queued; never P0/P3
    signal: str  # did.<NAME> or derived.<name>
    fault_id: str | None  # linked fault catalog entry, if any
    text: str  # the fixed template sentence
    text_source: str  # "fault" (the entry's rider_text) | "rule" (the rule's own text)
    condition: str  # above | below | rate_above | rate_below | absent
    threshold: float | None  # None for absent
    unit: str  # the signal's unit; <unit>/min for rate_*
    rate_window_s: float | None  # rate_* only
    sustain_s: float  # debounce
    clear_hysteresis: float | None  # None for absent
    cooldown_s: float
    max_spoken_per_ride: int
    gates: tuple[str, ...]  # names in ALERT_GATES that must all hold
    status: str  # PROVISIONAL | TUNED
    source_ref: str
    source_confidence: str  # high | medium | low
'''


def _py_call(cls: str, fields: dict[str, Any]) -> str:
    body = "".join(f"        {k}={v!r},\n" for k, v in fields.items())
    return f"    {cls}(\n{body}    )"


def generate_python(data: dict[str, Any], catalog: dict[str, Any]) -> str:
    gates = ",\n".join(_py_call("AlertGate", g) for g in _gates(data))
    rules = ",\n".join(_py_call("AlertRule", r) for r in resolve(data, catalog))
    return (
        PY_BANNER
        + "\nfrom __future__ import annotations\n\nfrom dataclasses import dataclass\n\n"
        + _PY_CLASSES
        + "\n\nALERT_GATES: dict[str, AlertGate] = {\n    g.name: g\n    for g in (\n"
        + textwrap.indent(gates, "    ")
        + ",\n    )\n}\n\nALERT_RULES: tuple[AlertRule, ...] = (\n"
        + rules
        + ",\n)\n\nALERT_RULES_BY_ID: dict[str, AlertRule] = {r.id: r for r in ALERT_RULES}\n"
    )


def _dart_str(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$")
    return f"'{escaped}'"


def _dart_value(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, str):
        return _dart_str(value)
    if isinstance(value, tuple):
        return "[" + ", ".join(_dart_str(v) for v in value) + "]"
    if isinstance(value, float):
        return repr(value)
    return str(value)


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.capitalize() for p in rest)


_DART_HEAD = """
/// Priority class of an in-ride alert (D-129 item 1). P0 and P3 are not rules.
enum AlertClass { p1, p2 }

/// What a rule tests (see faults/alert_rules.yaml).
enum AlertCondition { above, below, rateAbove, rateBelow, absent }

/// Comparison of a gate (a while-condition) against its value.
enum AlertGateOp { gt, ge, lt, le, eq }

/// A named while-condition on one defs signal; an invalid or stale value makes it false.
final class AlertGate {
  const AlertGate({
    required this.name,
    required this.signal,
    required this.op,
    required this.value,
    required this.unit,
    required this.source,
  });

  final String name;

  /// `did.<NAME>` or `derived.<name>`.
  final String signal;
  final AlertGateOp op;
  final double value;
  final String unit;
  final String source;
}

/// One in-ride alert rule (D-129). Times in seconds; `threshold` and
/// `clearHysteresis` are in `unit`.
final class AlertRule {
  const AlertRule({
    required this.id,
    required this.alertClass,
    required this.signal,
    required this.faultId,
    required this.text,
    required this.textSource,
    required this.condition,
    required this.threshold,
    required this.unit,
    required this.rateWindowS,
    required this.sustainS,
    required this.clearHysteresis,
    required this.cooldownS,
    required this.maxSpokenPerRide,
    required this.gates,
    required this.status,
    required this.sourceRef,
    required this.sourceConfidence,
  });

  /// `ALR-000`.
  final String id;
  final AlertClass alertClass;

  /// `did.<NAME>` or `derived.<name>`.
  final String signal;

  /// Linked fault catalog entry, if any.
  final String? faultId;

  /// The fixed template sentence.
  final String text;

  /// `fault` (the entry's rider_text) or `rule` (the rule's own text).
  final String textSource;
  final AlertCondition condition;

  /// Null for `absent`.
  final double? threshold;

  /// The signal's unit; `<unit>/min` for the rate conditions.
  final String unit;

  /// Rate conditions only.
  final double? rateWindowS;

  /// Debounce: the breach must hold this long.
  final double sustainS;

  /// Null for `absent`.
  final double? clearHysteresis;
  final double cooldownS;
  final int maxSpokenPerRide;

  /// Names in [alertGates] that must all hold.
  final List<String> gates;

  /// `PROVISIONAL` or `TUNED`.
  final String status;
  final String sourceRef;

  /// `high`, `medium` or `low`.
  final String sourceConfidence;
}

"""


def _dart_enum(value: str) -> str:
    return _camel(value)


def generate_dart(data: dict[str, Any], catalog: dict[str, Any]) -> str:
    gate_items = []
    for g in _gates(data):
        fields = {
            "name": _dart_str(g["name"]),
            "signal": _dart_str(g["signal"]),
            "op": f"AlertGateOp.{g['op']}",
            "value": repr(g["value"]),
            "unit": _dart_str(g["unit"]),
            "source": _dart_str(g["source"]),
        }
        body = "".join(f"    {k}: {v},\n" for k, v in fields.items())
        gate_items.append(f"  {_dart_str(g['name'])}: AlertGate(\n{body}  ),\n")
    rule_items = []
    for r in resolve(data, catalog):
        r = dict(r)
        r["alert_class"] = f"AlertClass.{r['alert_class'].lower()}"
        r["condition"] = f"AlertCondition.{_dart_enum(r['condition'])}"
        body = ""
        for k, v in r.items():
            lit = v if k in ("alert_class", "condition") else _dart_value(v)
            body += f"    {_camel(k)}: {lit},\n"
        rule_items.append(f"  AlertRule(\n{body}  ),\n")
    return (
        DART_BANNER
        + _DART_HEAD
        + "const Map<String, AlertGate> alertGates = {\n"
        + "".join(gate_items)
        + "};\n\nconst List<AlertRule> alertRules = [\n"
        + "".join(rule_items)
        + "];\n"
    )
